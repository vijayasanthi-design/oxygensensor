import numpy as np
import matplotlib.pyplot as plt
from sklearn.metrics import precision_recall_curve

# Get predicted probabilities for the test set from our best model (Tuned LightGBM)
test_probs = best_lgb_model.predict_proba(X_test)[:, 1]

# Compute precision-recall pairs for different thresholds
precisions, recalls, thresholds = precision_recall_curve(y_test, test_probs)

# Find the threshold that optimizes F1-score
f1_scores = [2 * (p * r) / (p + r) if (p + r) > 0 else 0 for p, r in zip(precisions, recalls)]
best_idx = np.argmax(f1_scores)
optimal_threshold = thresholds[best_idx] if best_idx < len(thresholds) else 0.5

print(f"--- Threshold Tuning (Tuned LightGBM) ---")
print(f"Default (0.50)   -> Precision: 0.6667 | Recall: 0.5000 | F1: 0.5714")

# Apply the optimized threshold
custom_preds = (test_probs >= optimal_threshold).astype(int)
opt_precision = precision_score(y_test, custom_preds, zero_division=0)
opt_recall = recall_score(y_test, custom_preds, zero_division=0)
opt_f1 = f1_score(y_test, custom_preds, zero_division=0)

print(f"Optimized ({optimal_threshold:.4f}) -> Precision: {opt_precision:.4f} | Recall: {opt_recall:.4f} | F1: {opt_f1:.4f}")

# Let's also find a threshold that guarantees at least 75% Recall for predictive maintenance safety
safe_idx = np.where(recalls >= 0.75)[0]
if len(safe_idx) > 0:
    # Choose the threshold in that subset with the highest precision
    best_safe_idx = safe_idx[np.argmax([precisions[i] for i in safe_idx])]
    safety_threshold = thresholds[best_safe_idx] if best_safe_idx < len(thresholds) else 0.3
    safety_preds = (test_probs >= safety_threshold).astype(int)
    safe_precision = precision_score(y_test, safety_preds, zero_division=0)
    safe_recall = recall_score(y_test, safety_preds, zero_division=0)
    safe_f1 = f1_score(y_test, safety_preds, zero_division=0)
    print(f"High-Safety ({safety_threshold:.4f}) -> Precision: {safe_precision:.4f} | Recall: {safe_recall:.4f} | F1: {safe_f1:.4f} (Catches {safe_recall*100:.1f}% of failures!)")

